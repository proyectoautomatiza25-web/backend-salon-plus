-- 3. STORAGE: BUCKET 'kingdom-assets' (Soluciona "Error al subir fotos")
-- Crear el bucket si no existe (vía SQL)
INSERT INTO storage.buckets (id, name, public) 
VALUES ('kingdom-assets', 'kingdom-assets', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Políticas de Storage para el bucket
DROP POLICY IF EXISTS "Acceso público de lectura kingdom-assets" ON storage.objects;
CREATE POLICY "Acceso público de lectura kingdom-assets"
ON storage.objects FOR SELECT
USING ( bucket_id = 'kingdom-assets' );

DROP POLICY IF EXISTS "Cualquiera puede subir fotos kingdom-assets" ON storage.objects;
CREATE POLICY "Cualquiera puede subir fotos kingdom-assets"
ON storage.objects FOR INSERT
WITH CHECK ( bucket_id = 'kingdom-assets' );

DROP POLICY IF EXISTS "Cualquiera puede actualizar sus fotos kingdom-assets" ON storage.objects;
CREATE POLICY "Cualquiera puede actualizar sus fotos kingdom-assets"
ON storage.objects FOR UPDATE
USING ( bucket_id = 'kingdom-assets' );

