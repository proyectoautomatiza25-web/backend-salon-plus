-- 1. TABLA DE VENTAS FUDO (Asegurar columnas para sync)
CREATE TABLE IF NOT EXISTS public.ventas_fudo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fudo_order_id TEXT UNIQUE NOT NULL,
    cliente_telefono TEXT,
    cliente_email TEXT,
    monto_total NUMERIC DEFAULT 0,
    puntos_generados INTEGER DEFAULT 0,
    conceptos TEXT,
    fecha_venta TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Habilitar RLS y políticas para ventas
ALTER TABLE public.ventas_fudo ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Lectura pública para dueños" ON public.ventas_fudo;
CREATE POLICY "Lectura pública para dueños" 
ON public.ventas_fudo FOR SELECT 
USING (true);

DROP POLICY IF EXISTS "Insertar desde Backend" ON public.ventas_fudo;
CREATE POLICY "Insertar desde Backend" 
ON public.ventas_fudo FOR INSERT 
WITH CHECK (true);

DROP POLICY IF EXISTS "Actualizar reclamos" ON public.ventas_fudo;
CREATE POLICY "Actualizar reclamos" 
ON public.ventas_fudo FOR UPDATE 
USING (true);

